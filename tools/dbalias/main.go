// Command dbalias publishes generated SQLC types through the models/db facade.
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const sqlcDir = "models/db/sqlc"
const outputPath = "models/db/sqlc_types.gen.go"

func collectTypes(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	names := make(map[string]struct{})
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, entry.Name()), nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				typ := spec.(*ast.TypeSpec)
				if typ.Name.IsExported() {
					names[typ.Name.Name] = struct{}{}
				}
			}
		}
	}
	result := make([]string, 0, len(names))
	for name := range names {
		result = append(result, name)
	}
	sort.Strings(result)
	return result, nil
}

func main() {
	names, err := collectTypes(sqlcDir)
	if err != nil {
		panic(err)
	}
	if len(names) == 0 {
		panic("SQLC produced no exported types")
	}
	var out strings.Builder
	out.WriteString("// Code generated by tools/dbalias. DO NOT EDIT.\n\n")
	out.WriteString("package db\n\n")
	out.WriteString("import sqlc \"github.com/datvtph41107/bdspro/models/db/sqlc\"\n\n")
	for _, name := range names {
		fmt.Fprintf(&out, "type %s = sqlc.%s\n", name, name)
	}
	source, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(outputPath, source, 0644); err != nil {
		panic(err)
	}
}
